#!/usr/bin/env python3
"""Generates the stencil header from the stencil object file.

Usage: extract.py STENCILS_O STENCILS_H
"""

import json
import re
import subprocess
import sys

DEPTHS = 9


def readobj(path):
    out = subprocess.run(
        ["llvm-readobj", "--elf-output-style=JSON", "--sections",
         "--section-data", "--section-relocations", "--symbols",
         "--demangle", path],
        check=True, capture_output=True, text=True).stdout
    return json.loads(out)[0]


def signed(addend):
    return addend - (1 << 64) if addend >= 1 << 63 else addend


def main(obj_path, header_path):
    obj = readobj(obj_path)
    sections = {s["Section"]["Index"]: s["Section"] for s in obj["Sections"]}
    by_name = {s["Name"]["Name"]: s for s in sections.values()}
    symbols = [s["Symbol"] for s in obj["Symbols"]]
    where = {s["Name"]["Name"]: (s["Section"]["Name"], s["Value"])
             for s in symbols}
    functions = {s["Section"]["Name"]: s["Name"]["Name"] for s in symbols
                 if s["Type"]["Name"] == "Function"}
    relocations = {s["Info"]: [r["Relocation"] for r in s["Relocations"]]
                   for s in sections.values() if s["Type"]["Name"] == "SHT_RELA"}

    rodata = bytearray()
    rodata_offset = {}

    def data_target(symbol, addend):
        section, value = where[symbol]
        if section not in rodata_offset:
            data = by_name[section]
            rodata.extend(bytes(-len(rodata) % 32))
            rodata_offset[section] = len(rodata)
            rodata.extend(data["SectionData"]["Bytes"])
        return rodata_offset[section] + value + addend

    stencils = {}
    for index, section in sections.items():
        flags = {f["Name"] for f in section["Flags"]["Flags"]}
        if "SHF_EXECINSTR" not in flags or section["Size"] == 0:
            continue
        name = functions[section["Name"]["Name"]]
        m = re.fullmatch(r"(?:void )?(\w+)(?:<(?:op::(\w+), )?(\d+)>)?\(.*\)",
                         name)
        if not m:
            sys.exit(f"extract.py: unexpected stencil {name}")
        kind, op, depth = m.groups()
        group = f"{kind}_{op}" if op else kind
        code = bytes(section["SectionData"]["Bytes"])
        patches = []
        for r in relocations.get(index, []):
            symbol, rtype, offset = (r["Symbol"]["Name"], r["Type"]["Name"],
                                     r["Offset"])
            addend = signed(r["Addend"])
            if symbol == "CONTINUE":
                if (rtype != "R_X86_64_PLT32" or offset != len(code) - 4
                        or code[-5] != 0xE9):
                    sys.exit(f"extract.py: {name} does not end in a jump to "
                             "CONTINUE")
                code = code[:-5]
            elif symbol == "HOLE" and rtype == "R_X86_64_64" and addend == 0:
                patches.append((offset, "true", 0))
            elif rtype == "R_X86_64_PC32" and symbol in where:
                patches.append((offset, "false", data_target(symbol, addend)))
            else:
                sys.exit(f"extract.py: {name} has unsupported relocation "
                         f"{rtype} to {symbol}")
        stencils.setdefault(group, {})[None if depth is None else int(depth)] = (
            name, code, patches)

    def array(data):
        return ", ".join(f"0x{b:02x}" for b in data)

    lines = [
        "// Generated by jit/extract.py. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace genetic {",
        "namespace jit {",
        "",
        "/** A location in a stencil to patch: with the node's value as 8 bytes",
        " * if `hole`, otherwise as the 4-byte offset from the location to",
        " * `rodata[target]`. */",
        "struct patch {",
        "  uint16_t offset;",
        "  bool hole;",
        "  int32_t target;",
        "};",
        "",
        "struct stencil {",
        "  const uint8_t *code;",
        "  uint16_t size;",
        "  const patch *patches;",
        "  uint16_t n_patches;",
        "};",
        "",
        "/** Constants the stencils load, to be copied next to the code. */",
        f"alignas(32) inline constexpr uint8_t rodata[] = {{{array(rodata)}}};",
        "",
        "/** The largest stencil, in bytes. */",
        "inline constexpr uint16_t max_size = "
        f"{max(len(c) for v in stencils.values() for _, c, _ in v.values())};",
        "",
        "namespace stencils {",
        "",
    ]
    for group, variants in sorted(stencils.items()):
        entries = {}
        for depth, (name, code, patches) in sorted(
                variants.items(), key=lambda v: -1 if v[0] is None else v[0]):
            ident = group if depth is None else f"{group}_{depth}"
            lines.append(f"// {name.split('(')[0]}")
            lines.append(f"inline constexpr uint8_t {ident}_code[] = "
                         f"{{{array(code)}}};")
            if patches:
                body = ", ".join(f"{{{o}, {h}, {t}}}" for o, h, t in patches)
                lines.append(f"inline constexpr patch {ident}_patches[] = "
                             f"{{{body}}};")
            patch_ref = f"{ident}_patches" if patches else "nullptr"
            entries[depth] = (f"{{{ident}_code, {len(code)}, {patch_ref}, "
                              f"{len(patches)}}}")
        if None in entries:
            lines.append(f"inline constexpr stencil {group} = {entries[None]};")
        else:
            row = ", ".join(entries.get(k, "{}") for k in range(DEPTHS))
            lines.append(f"/** Indexed by depth. */")
            lines.append(f"inline constexpr stencil {group}[{DEPTHS}] = "
                         f"{{{row}}};")
        lines.append("")
    lines += ["} // namespace stencils", "} // namespace jit",
              "} // namespace genetic", ""]
    with open(header_path, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip())
    main(sys.argv[1], sys.argv[2])
